    | عمداً از realpath استفاده نمی‌کنیم؛ چون اگر پوشه هنوز ساخته نشده
    | باشد realpath مقدار false برمی‌گرداند و دستور view:clear یا
    | optimize:clear با خطای "View path not found" متوقف می‌شود.
    |
    */

    'compiled' => env(
        'VIEW_COMPILED_PATH',
        storage_path('framework/views')
    ),

